def main():
    path=ROOT/'translation/players.json'
    ps=json.loads(path.read_text(encoding='utf-8'))
    byid={p['index']:p for p in ps}
    overrides=json.loads((ROOT/'translation/name_overrides.json').read_text(encoding='utf-8'))
    for line in NAMES.strip().splitlines():
        index,text=line.split(' ',1);ko=text.split('|');p=byid[int(index)]
        assert len(ko)==len(p['ja']),p
        p.update(ko=ko,match='reviewed_registration_or_foreign_name')
        overrides['by_index'][index]=ko
    path.write_text(json.dumps(ps,ensure_ascii=False,indent=2),encoding='utf-8')
    (ROOT/'translation/name_overrides.json').write_text(json.dumps(overrides,ensure_ascii=False,indent=2),encoding='utf-8')
    print('Translated',sum(bool(p['ko']) for p in ps),'of',len(ps))

if __name__=='__main__':main()
