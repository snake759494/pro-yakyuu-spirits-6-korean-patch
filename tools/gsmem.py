def addr32(bp, bw, x, y):
    """PSMCT32 픽셀 (x,y) 의 바이트 주소."""
    page = (y // 32) * bw + (x // 64)
    px, py = x % 64, y % 32
    block = BLOCK32[py // 8][px // 8]
    bx, by = px % 8, py % 8
    word = COL32[by][bx]
    return ((bp * 64 + page * 2048 + block * 64 + word) * 4) % (4 << 20)


def addr8(bp, bw, x, y):
    """PSMT8 픽셀의 바이트 주소 (페이지 128x64, 블록 16x16)."""
    page = (y // 64) * (bw // 2) + (x // 128)
    px, py = x % 128, y % 64
    block = BLOCK8[py // 16][px // 16]
    bx, by = px % 16, py % 16
    col = by // 4
    cy = by % 4
    idx = COL8[col % 2][cy][bx]
    return (bp * 256 + page * 8192 + block * 256 + col * 64 + idx) % (4 << 20)


def addr4(bp, bw, x, y):
    """PSMT4 픽셀의 니블 주소(=바이트주소*2 + 0/1). 페이지 128x128, 블록 32x16."""
    page = (y // 128) * (bw // 2) + (x // 128)
    px, py = x % 128, y % 128
    block = BLOCK4[py // 16][px // 32]
    bx, by = px % 32, py % 16
    col = by // 4
    cy = by % 4
    idx = COL4[col % 2][cy][bx]
    return ((bp * 256 + page * 8192 + block * 256 + col * 64) * 2 + idx) % (8 << 20)


def _as_np(vm):
    return vm if isinstance(vm, np.ndarray) else np.frombuffer(vm, np.uint8)


def index32(bp, bw, w, h):
    """(h, w) 배열: 각 픽셀의 바이트 주소."""
    idx = np.zeros((h, w), np.int64)
    for y in range(h):
        for x in range(w):
            idx[y, x] = addr32(bp, bw, x, y)
    return idx


def read32(vm, bp, bw, w, h):
    v = _as_np(vm)
    idx = index32(bp, bw, w, h)
    out = np.stack([v[idx + k] for k in range(4)], axis=-1)
    return out


def read8(vm, bp, bw, w, h):
    v = _as_np(vm)
    idx = np.array([[addr8(bp, bw, x, y) for x in range(w)] for y in range(h)], np.int64)
    return v[idx]


def read4(vm, bp, bw, w, h):
    v = _as_np(vm)
    a = np.array([[addr4(bp, bw, x, y) for x in range(w)] for y in range(h)], np.int64)
    b = v[a >> 1]
    return np.where(a & 1, b >> 4, b & 15).astype(np.uint8)
